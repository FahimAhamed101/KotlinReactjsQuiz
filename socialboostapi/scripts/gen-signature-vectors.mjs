// Generate signature test vectors from the SERVER's own implementation.
//
// The Android RequestSigner must reproduce lib/signature.js byte-for-byte, so the
// safest check is not "does my Kotlin look right" but "does my Kotlin produce the
// same bytes as the code that will actually verify it". This script imports the
// REAL lib/signature.js (via the ESM resolve hook, because lib/*.js uses
// extensionless specifiers) and prints canonical bodies + signatures for pinned
// timestamps/nonces, already formatted as Kotlin literals for RequestSignerTest.kt.
//
// Run with:
//   node --import ./scripts/register-esm-hook.mjs scripts/gen-signature-vectors.mjs
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { canonicalJson, sign } from '../lib/signature.js';

const require = createRequire(import.meta.url);
const { loadEnv } = require('./load-env.cjs');

const here = dirname(fileURLToPath(import.meta.url));

// Next.js loads .env for the server; plain Node does not. Without this the HMAC
// secret is the empty string and every vector is wrong in a way that still looks
// self-consistent (both sides empty-keyed).
loadEnv(resolve(here, '..', '.env'));

const APP_KEY = process.env.APP_KEY || '';
if (!APP_KEY) {
  console.error('APP_KEY is empty — refusing to emit vectors with an empty HMAC secret.');
  process.exit(1);
}

const TIMESTAMP = '1700000000';
const NONCE = 'abcdef0123456789';

// Deliberately includes the cases where a hand-written canonicaliser drifts:
// unsorted keys, nested objects, arrays, JSON null, booleans, whole vs fractional
// numbers, and a slash inside a URL (which must NOT be escaped).
const cases = [
  { name: 'GET, no body (server signs {})', method: 'GET', path: 'api/v6/me', body: {} },
  {
    name: 'POST login',
    method: 'POST',
    path: 'api/v6/login',
    body: { device_name: 'android', id: 'demo@ttboost.app', username: 'demo_user' },
  },
  {
    name: 'POST coins/check (numeric order_id)',
    method: 'POST',
    path: 'api/v6/coins/check',
    body: {
      order_id: 42,
      sec_uid: 'MS4wLjABAAAA',
      tt_username: 'demo_user',
      tiktok_username: 'target',
    },
  },
  {
    name: 'POST orders with a query string in the path',
    method: 'POST',
    path: 'api/v6/orders?page=1',
    body: {
      sec_uid: 'MS4wLjABAAAA',
      username: 'demo_user',
      url: 'https://www.tiktok.com/@demo_user',
      product_id: '2',
    },
  },
  {
    name: 'nested + array + null + bool + numbers',
    method: 'POST',
    path: 'api/v6/mixed',
    body: {
      url: 'https://example.com/a/b',
      list: [1, 2, 3],
      nested: { b: 1, a: 2 },
      nul: null,
      flag: true,
      float: 1.5,
      whole: 5,
    },
  },
  {
    name: 'whole-number float must not become 5.0',
    method: 'POST',
    path: 'api/v6/numbers',
    body: { int: 5, double: 5.0, big: 1234567890, small: 0.25 },
  },
  {
    name: 'string escapes: quote, backslash, newline, tab',
    method: 'POST',
    path: 'api/v6/strings',
    body: { quoted: 'say "hi"', slash: 'a\\b', multi: 'line1\nline2', tabbed: 'a\tb' },
  },
  {
    name: 'empty string and null-valued key',
    method: 'POST',
    path: 'api/v6/edge',
    body: { empty: '', nothing: null, list: [], obj: {} },
  },
];

/** Escape a value as a Kotlin normal string literal. */
function kstr(value) {
  return `"${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')}"`;
}

console.log('// ---- generated by scripts/gen-signature-vectors.mjs — do not edit by hand ----');
console.log(`// APP_KEY  = ${APP_KEY}`);
console.log(`// keyBytes = ${Buffer.from(APP_KEY.startsWith('base64:') ? APP_KEY.slice(7) : APP_KEY, APP_KEY.startsWith('base64:') ? 'base64' : 'utf8').toString('hex')}`);
console.log(`// timestamp = ${TIMESTAMP}`);
console.log(`// nonce     = ${NONCE}`);
console.log('');
console.log('private val TIMESTAMP = ' + kstr(TIMESTAMP));
console.log('private val NONCE = ' + kstr(NONCE));
console.log('');
console.log('private val vectors = listOf(');

for (const c of cases) {
  const canonical = canonicalJson(c.body);
  // Mirror verifySignature(): it signs `new URL(request.url).pathname`, so the
  // query string never reaches the canonical string. Signing the raw c.path here
  // would emit a vector that no correct client could ever match.
  const signedPath = c.path.split('?')[0].replace(/^\/+/, '');
  const signature = sign({
    method: c.method,
    path: signedPath,
    timestamp: TIMESTAMP,
    nonce: NONCE,
    body: canonical,
  });

  // A Kotlin raw string would break on `"""`, and the body JSON is fed through
  // JSONObject on the Kotlin side anyway, so emit ordinary escaped literals.
  const bodyJson = JSON.stringify(c.body);
  if (bodyJson.includes('$')) {
    console.error(`Case "${c.name}" contains '$', which kstr() would mangle.`);
    process.exit(1);
  }

  console.log('    Vector(');
  console.log(`        name = ${kstr(c.name)},`);
  console.log(`        method = ${kstr(c.method)},`);
  console.log(`        path = ${kstr(c.path)},`);
  console.log(`        body = ${kstr(bodyJson)},`);
  console.log(`        canonical = ${kstr(canonical)},`);
  console.log(`        signature = ${kstr(signature)},`);
  console.log('    ),');
}

console.log(')');
